"""Part 4: put real questions through POST /ask and write TEST_RESULTS.md.

    python scripts/run_questions.py                              # in-process, no server needed
    python scripts/run_questions.py --url http://localhost:8000  # against a running server

Needs ANTHROPIC_API_KEY (answers come from Claude) and a built index.
"""

import argparse
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app import config  # noqa: E402

# (question, page that should be cited - None means it isn't in the handbook)
QUESTIONS = [
    ("What is the attendance requirement?", None),  # the example from the brief
    ("How much does the bootcamp cost?", 16),
    ("How is my final grade calculated?", 14),
    ("When are the live classes?", 11),
    ("What are the minimum laptop requirements?", 5),
    ("What happens if my Capitec loan application fails?", 17),
    ("I want a different tutor. Who do I speak to?", 20),
    ("What final mark gives me a good chance of placement, and what do internships pay?", 24),
    ("What does a yellow tile on my calendar mean?", 9),
    ("How do I see how many XP points I need for the next level?", 22),
    ("What is the refund policy?", None),
    ("What is the pass mark for the MCQs?", None),  # MCQs are on p14, the pass mark isn't
]


def make_poster(url):
    if url:
        import httpx

        http = httpx.Client(base_url=url, timeout=120)
        return lambda q: http.post("/ask", json={"question": q})

    from fastapi.testclient import TestClient

    from app.api import app

    client = TestClient(app, raise_server_exceptions=False)
    return lambda q: client.post("/ask", json={"question": q})


def check(expected, source):
    if expected is None:
        return source is None
    return source is not None and str(expected) in source.replace(",", " ").split()


def cell(text):
    return (text or "-").replace("|", "\\|").replace("\n", " ")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--url", help="base URL of a running server; default runs the app in-process")
    parser.add_argument("--out", type=Path, default=ROOT / "TEST_RESULTS.md")
    args = parser.parse_args()

    post = make_poster(args.url)
    rows, passed = [], 0
    for i, (question, expected) in enumerate(QUESTIONS, start=1):
        response = post(question)
        body = response.json()
        if response.status_code != 200:
            sys.exit(f"Q{i} failed with {response.status_code}: {body.get('error')}")

        ok = check(expected, body["source"])
        passed += ok
        want = f"Page {expected}" if expected else "Not in handbook"
        print(f"[{'pass' if ok else 'FAIL'}] {question}\n       {body['source']}: {body['answer']}\n")
        rows.append(f"| {i} | {cell(question)} | {cell(body['source'])} | {cell(body['answer'])} "
                    f"| {want} | {'✅' if ok else '❌'} |")

    report = [
        "# Test results",
        "",
        f"Generated by `scripts/run_questions.py` on {date.today():%d %B %Y}. Every question went "
        f"through `POST /ask`, so this covers retrieval, generation and the API together.",
        "",
        f"- LLM: `{config.CLAUDE_MODEL}`",
        f"- Embeddings: `{config.EMBEDDING_MODEL}`, top {config.TOP_K} chunks, "
        f"similarity gate {config.MIN_SIMILARITY}",
        f"- **{passed}/{len(QUESTIONS)}** cited the expected page, or correctly said the "
        f"answer isn't in the handbook",
        "",
        "Page numbers are the PDF's own page numbers (what a PDF viewer shows). The numbers "
        "printed on pages 5-14 of the handbook are one lower than that.",
        "",
        "| # | Question | Source / Page | Answer | Expected | |",
        "|---|---|---|---|---|---|",
        *rows,
        "",
    ]
    args.out.write_text("\n".join(report), encoding="utf-8")
    print(f"{passed}/{len(QUESTIONS)} as expected. Written to {args.out.name}")


if __name__ == "__main__":
    main()
